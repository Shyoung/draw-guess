/** 대소문자 무시 중복 제거 (원본 표기는 첫 등장 것을 유지) */
function dedupe(list) {
  const seen = new Set();
  const out = [];
  for (const w of list) {
    const norm = String(w).normalize('NFC');
    const key = norm.toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(norm);
  }
  return out;
}

/** Fisher–Yates shuffle (복사본 반환) */
function shuffle(list) {
  const arr = list.slice();
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

// 카테고리 순서대로 평탄화. 여러 카테고리에 있는 단어는 앞 카테고리 소속으로 본다.
const CATEGORY_OF = new Map();
const KO_RAW = [];
for (const [name, list] of Object.entries(CATEGORIES)) {
  for (const w of list) {
    const norm = String(w).normalize('NFC');
    if (!CATEGORY_OF.has(norm.toLowerCase())) CATEGORY_OF.set(norm.toLowerCase(), name);
    KO_RAW.push(norm);
  }
}
const ko = dedupe(KO_RAW);

/** 단어의 카테고리 이름. 사전에 없는 단어(사용자 단어)는 null */
function categoryOf(word) {
  if (typeof word !== 'string') return null;
  return CATEGORY_OF.get(word.normalize('NFC').toLowerCase()) || null;
}

/**
 * 사용자 단어 파싱: 쉼표 구분, trim, 연속 공백 1개로, 1..20자, 중복 제거.
 * @param {unknown} str
 * @returns {string[]}
 */
function parseCustomWords(str) {
  if (typeof str !== 'string') return [];
  const out = [];
  const seen = new Set();
  for (const raw of str.split(',')) {
    const w = raw.normalize('NFC').trim().replace(/\s+/g, ' ');
    if (!w) continue;
    const len = Array.from(w).length;
    if (len < 1 || len > 20) continue;
    const key = w.toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(w);
  }
  return out;
}

/**
 * 후보 단어 선택.
 *  - 한국어 기본 풀에 customWords 병합
 *  - customWordsOnly 이고 사용자 단어가 count개 이상이면 사용자 단어만 사용
 *  - exclude(이미 나온 단어)는 가능하면 피하고, 부족하면 사용한 단어로 채움
 *  - count개의 서로 다른 무작위 단어 반환 (풀이 부족하면 가능한 만큼)
 * @param {object} settings
 * @param {Set<string>} exclude
 * @param {number} count
 * @returns {string[]}
 */
function pickWords(settings, exclude, count) {
  const s = settings || {};
  const ex = exclude instanceof Set ? exclude : new Set();
  const n = Math.max(1, Math.floor(Number(count) || 3));

  const custom = parseCustomWords(s.customWords);
  let pool;
  if (s.customWordsOnly && custom.length >= n) {
    pool = custom;
  } else {
    pool = dedupe(ko.concat(custom));
  }

  const unused = shuffle(pool.filter((w) => !ex.has(w)));
  if (unused.length >= n) return unused.slice(0, n);
  const used = shuffle(pool.filter((w) => ex.has(w)));
  return unused.concat(used).slice(0, n);
}

